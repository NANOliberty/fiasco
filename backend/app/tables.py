def lookup_aftermath(color: str | None, value: int) -> dict:
    """후기 표 조회. color 가 없으면(흑백 동점/주사위 없음) 최악의 결과로 처리한다."""
    key = color if color in AFTERMATH_TABLE else "black"
    effective = value if color else 0
    for low, high, title, text in AFTERMATH_TABLE[key]:
        if effective >= low and (high is None or effective <= high):
            return {
                "color": color,
                "value": effective,
                "range": f"{low}+" if high is None else (str(low) if low == high else f"{low}~{high}"),
                "title": title,
                "text": text,
            }
    raise AssertionError("unreachable: aftermath table has no matching range")


