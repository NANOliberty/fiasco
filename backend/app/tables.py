def twist_text(category: int, element: int) -> tuple[str, str]:
    """1-based (분류, 요소) → (분류명, 요소 텍스트)."""
    if not (1 <= category <= 6 and 1 <= element <= 6):
        raise ValueError("비틀기 표의 분류와 요소는 1~6 사이여야 합니다.")
    entry = TWIST_TABLE[category - 1]
    return entry["category"], entry["elements"][element - 1]


